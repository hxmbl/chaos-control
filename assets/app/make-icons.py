#!/usr/bin/env python3
"""Generate every Chaos Control app icon from one geometry: the halving mark.

The mark is a broken ring at one stroke weight. Each segment is half the one
before it, measured cap to cap, so the last one is a dot. The largest segment
is centred top-left and the chain runs clockwise.

Writes (next to this script)
  app-icon.svg          flattened source: graphite tile + mark
  app-icon-1024.png     dock icon (dock.rs) and Linux bundle icon
  app-icon.ico          Windows, 16-256
  AppIcon.icns          pre-Tahoe macOS, 16-1024 @1x/@2x
  ChaosControl.icon/    Icon Composer bundle for macOS 26 Liquid Glass. Each
                        segment is its own glass layer. Compiling it needs
                        actool from Xcode 26+ (cargo-bundle does not do this).

Needs: pip install cairosvg pillow
Run: python3 assets/app/make-icons.py
"""
import io
import json
import math
import shutil
import struct
from pathlib import Path

import cairosvg
from PIL import Image

HERE = Path(__file__).resolve().parent

# Mark geometry on a 1024 canvas, before scaling.
R = 300.0          # ring radius (centre of stroke)
STROKE = 104.0     # one weight for every segment
GAP = 8.0          # visible gap between segments, degrees
SEGMENTS = 4       # big, half, quarter, dot
START = 225.0      # centre of the largest segment (SVG degrees, y down): top-left

TILE_TOP = "#2C2C2C"
TILE_BOTTOM = "#141414"
INK = "#F5F5F7"
FLAT_SCALE = 0.74   # mark size inside the 824 px pre-Tahoe tile
GLASS_SCALE = 0.86  # mark size on the Icon Composer canvas (the whole shape)


def segments():
    """(start_deg, visible_deg) for each segment, cap to cap."""
    cap = math.degrees(STROKE / R)
    v0 = (360 - GAP * SEGMENTS) / sum(0.5 ** k for k in range(SEGMENTS))
    a = START - v0 / 2
    out = []
    for k in range(SEGMENTS):
        v = v0 * 0.5 ** k
        out.append((a, v, cap))
        a += v + GAP
    return out


def seg_path(a, v, cap, scale, c=512.0):
    """Filled outline of one round-capped arc segment, scaled about the centre."""
    r, h = R * scale, STROKE * scale / 2
    s, e = math.radians(a + cap / 2), math.radians(a + v - cap / 2)
    if e - s < 1e-3:  # a dot
        x, y = c + r * math.cos(s), c + r * math.sin(s)
        return (f"M {x - h:.2f} {y:.2f} A {h:.2f} {h:.2f} 0 1 0 {x + h:.2f} {y:.2f} "
                f"A {h:.2f} {h:.2f} 0 1 0 {x - h:.2f} {y:.2f} Z")
    big = 1 if e - s > math.pi else 0
    p = lambda rad, t: (c + rad * math.cos(t), c + rad * math.sin(t))
    o0, o1, i1, i0 = p(r + h, s), p(r + h, e), p(r - h, e), p(r - h, s)
    return (f"M {o0[0]:.2f} {o0[1]:.2f} A {r + h:.2f} {r + h:.2f} 0 {big} 1 {o1[0]:.2f} {o1[1]:.2f} "
            f"A {h:.2f} {h:.2f} 0 0 1 {i1[0]:.2f} {i1[1]:.2f} "
            f"A {r - h:.2f} {r - h:.2f} 0 {big} 0 {i0[0]:.2f} {i0[1]:.2f} "
            f"A {h:.2f} {h:.2f} 0 0 1 {o0[0]:.2f} {o0[1]:.2f} Z")


def flat_svg():
    paths = "\n".join(f'<path d="{seg_path(a, v, cap, FLAT_SCALE)}"/>' for a, v, cap in segments())
    return f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024">
<!-- Generated by make-icons.py; edit the script, not this file. -->
<defs>
<linearGradient id="bg" x1="0" y1="0" x2="0" y2="1">
<stop offset="0" stop-color="{TILE_TOP}"/>
<stop offset="1" stop-color="{TILE_BOTTOM}"/>
</linearGradient>
<linearGradient id="rim" x1="0" y1="0" x2="0" y2="1">
<stop offset="0" stop-color="#FFFFFF" stop-opacity="0.16"/>
<stop offset="0.5" stop-color="#FFFFFF" stop-opacity="0.03"/>
<stop offset="1" stop-color="#FFFFFF" stop-opacity="0.06"/>
</linearGradient>
</defs>
<rect x="100.0" y="100.0" width="824" height="824" rx="185" fill="url(#bg)"/>
<rect x="102.0" y="102.0" width="820" height="820" rx="183" fill="none" stroke="url(#rim)" stroke-width="4"/>
<g fill="{INK}">
{paths}
</g>
</svg>
'''


def png_bytes(img, size, quantize=True):
    b = io.BytesIO()
    im = img.resize((size, size), Image.LANCZOS)
    if quantize:
        im = im.quantize(256, method=Image.Quantize.FASTOCTREE)
    im.save(b, "PNG", optimize=True)
    return b.getvalue()


def write_icns(img, path):
    types = [("icp4", 16), ("icp5", 32), ("icp6", 64), ("ic07", 128), ("ic08", 256),
             ("ic09", 512), ("ic10", 1024), ("ic11", 32), ("ic12", 64), ("ic13", 256), ("ic14", 512)]
    body = b"".join(t.encode() + struct.pack(">I", 8 + len(d)) + d
                    for t, d in ((t, png_bytes(img, s)) for t, s in types))
    path.write_bytes(b"icns" + struct.pack(">I", 8 + len(body)) + body)


def rgba(hexstr, a=1.0):
    r, g, b = (int(hexstr[i:i + 2], 16) / 255 for i in (1, 3, 5))
    return f"extended-srgb:{r:.5f},{g:.5f},{b:.5f},{a:.5f}"


def write_icon_bundle():
    root = HERE / "ChaosControl.icon"
    shutil.rmtree(root, ignore_errors=True)
    (root / "Assets").mkdir(parents=True)
    names = ["Segment 1 (largest)", "Segment 2", "Segment 3", "Segment 4 (dot)"]
    layers = []
    for k, (a, v, cap) in enumerate(segments()):
        fname = f"segment-{k + 1}.svg"
        (root / "Assets" / fname).write_text(
            '<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024">\n'
            f'  <path fill="#000000" d="{seg_path(a, v, cap, GLASS_SCALE)}"/>\n</svg>\n')
        layers.append({
            "name": names[k],
            "image-name": fname,
            "glass": True,
            "fill-specializations": [
                {"value": {"solid": rgba("#1C1C1E")}},
                {"appearance": "dark", "value": {"solid": rgba(INK)}},
                {"appearance": "tinted", "value": {"solid": rgba("#FFFFFF")}},
            ],
        })
    doc = {
        "fill-specializations": [
            {"value": {"linear-gradient": [rgba("#FFFFFF"), rgba("#DCDCDE")]}},
            {"appearance": "dark", "value": {"linear-gradient": [rgba(TILE_TOP), rgba(TILE_BOTTOM)]}},
        ],
        "groups": [{
            "name": "Halving mark",
            "layers": layers,
            "lighting": "individual",
            "specular": True,
            "shadow": {"kind": "neutral", "opacity": 0.5},
            "translucency": {"enabled": True, "value": 0.2},
        }],
        "supported-platforms": {"squares": ["macOS"]},
    }
    (root / "icon.json").write_text(json.dumps(doc, indent=2) + "\n")


def main():
    svg = flat_svg()
    (HERE / "app-icon.svg").write_text(svg)
    png = cairosvg.svg2png(bytestring=svg.encode(), output_width=1024, output_height=1024)
    (HERE / "app-icon-1024.png").write_bytes(png)
    img = Image.open(io.BytesIO(png)).convert("RGBA")
    img.save(HERE / "app-icon.ico", sizes=[(s, s) for s in (16, 24, 32, 48, 64, 128, 256)])
    write_icns(img, HERE / "AppIcon.icns")
    write_icon_bundle()


if __name__ == "__main__":
    main()
