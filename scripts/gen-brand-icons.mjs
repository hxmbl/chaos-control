// Copies the few brand icons the app uses out of local Iconify JSON packages into
// src/icons/brands.ts, so they ship inside the bundle and never hit the Iconify API.
// Run: node scripts/gen-brand-icons.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const sets = {
  "simple-icons": JSON.parse(readFileSync(require.resolve("@iconify-json/simple-icons/icons.json"), "utf8")),
  logos: JSON.parse(readFileSync(require.resolve("@iconify-json/logos/icons.json"), "utf8")),
};

// export name -> [set, icon name, optional body transform]
const wanted = {
  github: ["simple-icons", "github"],
  linear: ["simple-icons", "linear"],
  vercel: ["simple-icons", "vercel"],
  zed: ["simple-icons", "zedindustries"],
  // Agents
  openai: ["simple-icons", "openai"],
  claude: ["simple-icons", "claude"],
  // logos:devin is multi-colour-ready but ships unfilled; tint it like the others.
  devin: ["logos", "devin", (b) => b.replaceAll("<path ", '<path fill="currentColor" ')],
  githubCopilot: ["simple-icons", "githubcopilot"],
  mistral: ["simple-icons", "mistralai"],
  // opencode's real mark has a lighter lower half inside the frame; add it back.
  opencode: [
    "simple-icons",
    "opencode",
    (b) => b + '<path fill="currentColor" fill-opacity=".38" d="M17 11.2H7v8h10z"/>',
  ],
  pi: ["simple-icons", "pi"],
};

let out = `// Generated by scripts/gen-brand-icons.mjs from @iconify-json/simple-icons and @iconify-json/logos (both CC0-1.0). Do not edit.
import type { IconifyIcon } from "@iconify/react";

`;
for (const [exportName, [setName, iconName, transform]] of Object.entries(wanted)) {
  const set = sets[setName];
  const icon = set.icons[iconName];
  if (!icon) throw new Error(`${setName} has no "${iconName}"`);
  const data = {
    body: transform ? transform(icon.body) : icon.body,
    width: icon.width ?? set.width ?? 24,
    height: icon.height ?? set.height ?? 24,
  };
  out += `export const ${exportName}: IconifyIcon = ${JSON.stringify(data)};\n`;
}

writeFileSync(new URL("../src/icons/brands.ts", import.meta.url), out);
console.log(`wrote ${Object.keys(wanted).length} icons`);
