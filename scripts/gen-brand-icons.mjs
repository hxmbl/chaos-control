// Copies the few brand icons the app uses out of @iconify-json/simple-icons into
// src/icons/brands.ts, so they ship inside the bundle and never hit the Iconify API.
// Run: node scripts/gen-brand-icons.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const set = JSON.parse(readFileSync(require.resolve("@iconify-json/simple-icons/icons.json"), "utf8"));

// export name -> simple-icons name
const wanted = {
  github: "github",
  linear: "linear",
  vercel: "vercel",
  zed: "zedindustries",
};

let out = `// Generated by scripts/gen-brand-icons.mjs from @iconify-json/simple-icons (CC0-1.0). Do not edit.
import type { IconifyIcon } from "@iconify/react";

`;
for (const [exportName, iconName] of Object.entries(wanted)) {
  const icon = set.icons[iconName];
  if (!icon) throw new Error(`simple-icons has no "${iconName}"`);
  const data = {
    body: icon.body,
    width: icon.width ?? set.width ?? 24,
    height: icon.height ?? set.height ?? 24,
  };
  out += `export const ${exportName}: IconifyIcon = ${JSON.stringify(data)};\n`;
}

writeFileSync(new URL("../src/icons/brands.ts", import.meta.url), out);
console.log(`wrote ${Object.keys(wanted).length} icons`);
